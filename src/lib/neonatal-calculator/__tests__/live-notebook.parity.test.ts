import { notebookBatchRecord } from "../notebook-results";
import { execFileSync } from "node:child_process";
import { describe, expect, it } from "vitest";
import { calculateRecommendations } from "../recommendation-engine";
import { processBatchTable } from "../batch-engine";
import { buildBatchResultWorkbook } from "../batch-workbook";
import { summarizeBatch } from "../batch-statistics";
import type { PatientInput } from "../types";

// Historical v18/v19 regression evidence. v20 acceptance has its own explicit gate:
// npm run test:neonatal:v20. Passing this suite alone does not establish v20 parity.
// The reference is generated by executing the original Python, not copied TS logic.
const oracle = JSON.parse(execFileSync(process.env.PYTHON || "python", ["scripts/neonatal-notebook-oracle.py"], { encoding: "utf8", maxBuffer: 16 * 1024 * 1024 }));
const batch = processBatchTable([oracle.header, ...oracle.inputRows]);
describe("live Python notebook v18 differential parity", () => {
  it("executes every notebook self-check, including widget/form and batch conditions", () => {
    console.log(`Oracle: ${oracle.notebookChecks.length} notebook checks; ${oracle.recommendations.length} boundary/renal profiles; SHA256 ${oracle.source.sha256}`);
    expect(oracle.source.sha256).toBe("1ecf1816c585f996e0aa313ec9a50c469330405cd338f1ac286248f230f9a846");
    expect(oracle.notebookChecks).toHaveLength(92);
    expect(oracle.notebookChecks.filter((c: { Status: string }) => c.Status !== "LULUS")).toEqual([]);
  });
  it("matches all generated boundary and renal profiles", () => {
    const failures: unknown[] = [];
    for (const row of oracle.recommendations as {input: PatientInput; expected: {rsDose: number[]; litDose: number[]; rsInterval: (number | null)[]; litInterval: number[]}}[]) {
      const result = calculateRecommendations(row.input);
      for (const [rec, dose, hours] of [
        [result.recommendations.institutionalPrimary, row.expected.rsDose, row.expected.rsInterval],
        [result.recommendations.anmf2024, row.expected.litDose, row.expected.litInterval],
      ] as const) {
        const interval = rec.interval.kind === "single-dose-only" ? [null, null] : rec.interval.kind === "single" ? [rec.interval.hours, rec.interval.hours] : rec.interval.kind === "continuous-range" ? [rec.interval.minHours, rec.interval.maxHours] : [];
        if (JSON.stringify(interval) !== JSON.stringify(hours) || Math.abs(rec.dose.minTotalMg! - dose[0]) > 1e-8 || Math.abs(rec.dose.maxTotalMg! - dose[1]) > 1e-8) failures.push({input: row.input, actual: rec, expected: {dose, hours}});
      }
    }
    expect(failures).toEqual([]);
  });
  it("matches the original batch row IDs and exposes exact reference fields", () => {
    expect(batch.successCount, JSON.stringify(batch.rows.slice(0,2))).toBe(30); expect(batch.errorCount).toBe(4);
    expect(batch.rows.filter(r => r.status === "berhasil").map(r => r.patientCode)).toEqual(oracle.batchRecords.map((r: Record<string, unknown>) => r["Kode Pasien"]));
  });
  it("retains internal research variables from the historical v18 reference", () => {
    const failures: unknown[] = [];
    const extra=processBatchTable([oracle.header,...oracle.extraInputRows]);
    expect(extra.successCount).toBe(oracle.extraRecords.length);
    for (const row of [...batch.rows,...extra.rows]) {
      if (row.status !== "berhasil") continue;
      const actual = notebookBatchRecord(row);
      const expected = [...oracle.batchRecords,...oracle.extraRecords].find((r: Record<string,unknown>) => r["Kode Pasien"] === row.patientCode);
      for (const key of Object.keys(actual).filter(key => key.startsWith("_") && !key.startsWith("_dev_"))) {
        if (typeof actual[key] === "number" && typeof expected[key] === "number" ? Math.abs(Number(actual[key])-expected[key]) > 1e-9 : actual[key] !== expected[key]) failures.push({id:row.patientCode,key,actual:actual[key],expected:expected[key]});
      }
    }
    expect(failures).toEqual([]);
  });
  it("matches warning levels and reasons on every generated patient profile", () => {
    for (const row of oracle.recommendations) {
      const result=calculateRecommendations(row.input);
      const levels={critical:"bahaya",warning:"perhatian",info:"informasi"};
      expect(result.globalWarnings.filter(w=>w.title).map(w=>[levels[w.severity],w.title]),JSON.stringify(row.input)).toEqual(row.expected.warnings);
    }
  });
  it("keeps the historical batch workbook structurally usable while v20 owns its public export contract", async () => {
    const ExcelJS=await import("exceljs"); const book=new ExcelJS.Workbook();
    await book.xlsx.load(Buffer.from(await buildBatchResultWorkbook(batch)) as unknown as import("exceljs").Buffer);
    const sheet=book.getWorksheet("Hasil per Pasien")!;
    expect(sheet.rowCount).toBe(31);
    expect(sheet.getRow(1).getCell(1).value).toBe("Kode Pasien");
    expect(sheet.getRow(2).getCell(1).value).toBe("T01");
  });
  it("matches category distributions and all denominators", () => {
    const result=summarizeBatch(batch);
    for (const [kind,calculation,group,reference,total,same,,higher,,lower] of oracle.summary) {
      for (const [category,n] of [["sesuai",same],["berlebih",higher],["kurang",lower]]) {
        const actual=result.counts.find(r=>r.group === (group==="SEMUA"?"Keseluruhan":group.toLowerCase()) && r.metric === kind+" "+calculation.toLowerCase() && r.reference === (reference==="vs Pedoman RS"?"Pedoman Rumah Sakit":"Literatur Terkini") && r.category===category)!;
        expect(actual.total).toBe(total); expect(actual.count).toBe(n);
      }
    }
  });
});
